-- ---------------------------------------------------------------------------
-- 步骤 0：先看行数与表大小，确认窗口够用
--   RENAME 本身是元数据操作（很快），真正耗时的是步骤 3 的索引重建。
-- ---------------------------------------------------------------------------
SELECT COUNT(*) AS row_cnt FROM z_ctc_surl_mapping;

SELECT TABLE_NAME, TABLE_ROWS, DATA_LENGTH, INDEX_LENGTH
FROM information_schema.TABLES
WHERE TABLE_SCHEMA = DATABASE()
  AND TABLE_NAME IN ('z_ctc_surl_mapping', 'z_surl_mapping');

-- ---------------------------------------------------------------------------
-- 步骤 1：确认新表名没被占用（有输出就停手，先人工确认那张表是什么）
-- ---------------------------------------------------------------------------
SELECT TABLE_NAME
FROM information_schema.TABLES
WHERE TABLE_SCHEMA = DATABASE()
  AND TABLE_NAME = 'z_surl_mapping';
-- 期望：0 行。若非 0，说明 z_surl_mapping 已存在，**不要继续**，先比对内容。

-- ---------------------------------------------------------------------------
-- 步骤 2：改名（RENAME 保留索引定义，不需要重建）
-- ---------------------------------------------------------------------------
RENAME TABLE z_ctc_surl_mapping TO z_surl_mapping;

-- ---------------------------------------------------------------------------
-- 步骤 3：补上 schema.sql 里新增的 created_at 索引
--   （旧表若已带同名索引，这句会报 Duplicate key name，先用
--     SHOW INDEX FROM z_surl_mapping;
--    确认后再决定是否执行）
--   控制台列表按创建时间倒序翻页 + 清理过期短链的扫描入口都靠它。
-- ---------------------------------------------------------------------------
CREATE INDEX idx_z_surl_mapping_created_at ON z_surl_mapping (created_at);

